# index_workshop.ps1 - regenerate the workshop catalog and note index.
#
# Reads the YAML front matter of
#   workshop/tools/*/README.md   -> workshop/CATALOG.md
#   workshop/notes/*.md          -> workshop/notes/INDEX.md
# and rewrites both index files. Output is deterministic (no timestamps), so
# running it twice in a row produces byte-identical files.
#
# -Check verifies the indexes are up to date without writing, which is what a
# hook or a pre-commit check should call.
#
# NOTE: This script is ASCII-only on purpose (PowerShell 5.1 parses a
# BOM-less UTF-8 .ps1 as ANSI and multi-byte comment characters can corrupt
# the next statement). Japanese headings are built from code points below.
#
# Usage:
#   powershell -File .claude/tools/index_workshop.ps1 [-Root workshop] [-Check]
#
# Exit code: 0 = indexes written (or already up to date under -Check)
#            1 = a front matter block is missing/broken, or -Check found drift
#            2 = argument / environment error (no workshop root)
param(
    [string]$Root = "workshop",
    [switch]$Check
)

$ErrorActionPreference = "Stop"

$UTF8 = [System.Text.UTF8Encoding]::new($false)

function Read-Utf8([string]$p) { return [System.IO.File]::ReadAllText($p, $UTF8) }
function Write-Utf8([string]$p, [string]$t) { [System.IO.File]::WriteAllText($p, $t, $UTF8) }

# Japanese headings/labels as code points (see the ASCII-only note above).
$J = @{
    Catalog   = [string][char]0x5DE5 + [char]0x623F + [char]0x30C4 + [char]0x30FC + [char]0x30EB + [char]0x4E00 + [char]0x89A7  # tool catalog
    NoteIndex = [string][char]0x30CE + [char]0x30FC + [char]0x30C8 + [char]0x4E00 + [char]0x89A7                                 # note index
    Name      = [string][char]0x540D + [char]0x524D                                                                              # name
    Summary   = [string][char]0x8981 + [char]0x7D04                                                                              # summary
    Status    = [string][char]0x72B6 + [char]0x614B                                                                              # status
    Lang      = [string][char]0x8A00 + [char]0x8A9E                                                                              # language
    Tags      = [string][char]0x30BF + [char]0x30B0                                                                              # tags
    Updated   = [string][char]0x66F4 + [char]0x65B0                                                                              # updated
    Date      = [string][char]0x65E5 + [char]0x4ED8                                                                              # date
    Title     = [string][char]0x30BF + [char]0x30A4 + [char]0x30C8 + [char]0x30EB                                                # title
    Empty     = [string][char]0x307E + [char]0x3060 + [char]0x3042 + [char]0x308A + [char]0x307E + [char]0x305B + [char]0x3093   # none yet
}

$genNote = "<!-- GENERATED by .claude/tools/index_workshop.ps1 - do not edit by hand -->"

if (-not (Test-Path $Root)) {
    Write-Output "ERROR: workshop root not found: $Root"
    Write-Output "HINT: create it with new_tool.ps1 or new_note.ps1 first."
    exit 2
}

function Get-FrontMatter([string]$path) {
    # Returns a hashtable of the YAML front matter, or $null when absent/broken.
    $lines = (Read-Utf8 $path) -split "`r?`n"
    if ($lines.Count -lt 2 -or $lines[0].Trim() -ne "---") { return $null }
    $map = @{}
    for ($i = 1; $i -lt $lines.Count; $i++) {
        $line = $lines[$i]
        if ($line.Trim() -eq "---") { return $map }
        $m = [regex]::Match($line, '^([A-Za-z_][A-Za-z0-9_]*)\s*:\s*(.*)$')
        if ($m.Success) {
            $v = $m.Groups[2].Value.Trim()
            if ($v.StartsWith("[") -and $v.EndsWith("]")) {
                $v = $v.Substring(1, $v.Length - 2).Trim()
            }
            $map[$m.Groups[1].Value] = $v
        }
    }
    return $null  # closing --- never found
}

function Get-Field($map, [string]$key) {
    if ($map.ContainsKey($key) -and -not [string]::IsNullOrWhiteSpace($map[$key])) {
        return $map[$key]
    }
    return "-"
}

function To-Posix([string]$p) { return $p.Replace("\", "/") }

# .NET Framework 4.x (PowerShell 5.1) has no Path.GetRelativePath, so strip
# the current directory prefix by hand.
$script:BaseDir = (Get-Location).Path.TrimEnd('\', '/')
function To-Relative([string]$full) {
    $prefix = $script:BaseDir + [System.IO.Path]::DirectorySeparatorChar
    if ($full.StartsWith($prefix, [System.StringComparison]::OrdinalIgnoreCase)) {
        return To-Posix $full.Substring($prefix.Length)
    }
    return To-Posix $full
}

$problems = @()

# ---- catalog -------------------------------------------------------------
$toolsDir = Join-Path $Root "tools"
$toolRows = @()
if (Test-Path $toolsDir) {
    $readmes = @(Get-ChildItem -LiteralPath $toolsDir -Directory |
        Sort-Object Name |
        ForEach-Object { Join-Path $_.FullName "README.md" } |
        Where-Object { Test-Path $_ })
    foreach ($r in $readmes) {
        $fm = Get-FrontMatter $r
        $rel = To-Relative $r
        if ($null -eq $fm) {
            $problems += "BROKEN-FRONTMATTER: $rel"
            continue
        }
        # Links in CATALOG.md are relative to CATALOG.md itself, which sits
        # at the workshop root - so "tools/<name>", not the repo-relative path.
        $dir = "tools/" + (Split-Path -Leaf (Split-Path -Parent $r))
        $toolRows += [pscustomobject]@{
            Name    = Get-Field $fm "name"
            Summary = Get-Field $fm "summary"
            Status  = Get-Field $fm "status"
            Lang    = Get-Field $fm "lang"
            Tags    = Get-Field $fm "tags"
            Updated = Get-Field $fm "updated"
            Path    = $dir
        }
    }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("# " + $J.Catalog)
[void]$sb.AppendLine()
[void]$sb.AppendLine($genNote)
[void]$sb.AppendLine()
if ($toolRows.Count -eq 0) {
    [void]$sb.AppendLine($J.Empty)
} else {
    [void]$sb.AppendLine("| $($J.Name) | $($J.Summary) | $($J.Status) | $($J.Lang) | $($J.Tags) | $($J.Updated) |")
    [void]$sb.AppendLine("|---|---|---|---|---|---|")
    foreach ($t in $toolRows) {
        [void]$sb.AppendLine("| [$($t.Name)]($($t.Path)/README.md) | $($t.Summary) | $($t.Status) | $($t.Lang) | $($t.Tags) | $($t.Updated) |")
    }
}
$catalogText = $sb.ToString()

# ---- note index ----------------------------------------------------------
$notesDir = Join-Path $Root "notes"
$noteRows = @()
if (Test-Path $notesDir) {
    $notes = @(Get-ChildItem -LiteralPath $notesDir -Filter *.md -File |
        Where-Object { $_.Name -ne "INDEX.md" } |
        Sort-Object Name -Descending)
    foreach ($n in $notes) {
        $fm = Get-FrontMatter $n.FullName
        $rel = To-Relative $n.FullName
        if ($null -eq $fm) {
            $problems += "BROKEN-FRONTMATTER: $rel"
            continue
        }
        $noteRows += [pscustomobject]@{
            Date   = Get-Field $fm "date"
            Title  = Get-Field $fm "title"
            Tags   = Get-Field $fm "tags"
            Status = Get-Field $fm "status"
            File   = $n.Name
        }
    }
}

$sb2 = New-Object System.Text.StringBuilder
[void]$sb2.AppendLine("# " + $J.NoteIndex)
[void]$sb2.AppendLine()
[void]$sb2.AppendLine($genNote)
[void]$sb2.AppendLine()
if ($noteRows.Count -eq 0) {
    [void]$sb2.AppendLine($J.Empty)
} else {
    [void]$sb2.AppendLine("| $($J.Date) | $($J.Title) | $($J.Tags) | $($J.Status) |")
    [void]$sb2.AppendLine("|---|---|---|---|")
    foreach ($n in $noteRows) {
        [void]$sb2.AppendLine("| $($n.Date) | [$($n.Title)]($($n.File)) | $($n.Tags) | $($n.Status) |")
    }
}
$indexText = $sb2.ToString()

# ---- write or check ------------------------------------------------------
$catalogPath = Join-Path $Root "CATALOG.md"
$indexPath = Join-Path $notesDir "INDEX.md"

function Test-Same([string]$path, [string]$want) {
    if (-not (Test-Path $path)) { return $false }
    return ((Read-Utf8 $path) -eq $want)
}

if ($Check) {
    $stale = @()
    if (-not (Test-Same $catalogPath $catalogText)) { $stale += (To-Posix $catalogPath) }
    if ($noteRows.Count -gt 0 -or (Test-Path $indexPath)) {
        if (-not (Test-Same $indexPath $indexText)) { $stale += (To-Posix $indexPath) }
    }
    foreach ($p in $problems) { Write-Output $p }
    foreach ($s in $stale) { Write-Output "STALE: $s" }
    if ($problems.Count -gt 0 -or $stale.Count -gt 0) {
        Write-Output "RESULT: NG ($($problems.Count) broken, $($stale.Count) stale) - run without -Check to fix"
        exit 1
    }
    Write-Output "RESULT: up to date ($($toolRows.Count) tools, $($noteRows.Count) notes)"
    exit 0
}

Write-Utf8 $catalogPath $catalogText
Write-Output "WROTE: $(To-Posix $catalogPath) ($($toolRows.Count) tools)"

if ($noteRows.Count -gt 0 -or (Test-Path $notesDir)) {
    New-Item -ItemType Directory -Path $notesDir -Force | Out-Null
    Write-Utf8 $indexPath $indexText
    Write-Output "WROTE: $(To-Posix $indexPath) ($($noteRows.Count) notes)"
}

foreach ($p in $problems) { Write-Output $p }
if ($problems.Count -gt 0) {
    Write-Output "RESULT: NG - $($problems.Count) file(s) have missing or broken front matter"
    exit 1
}

Write-Output "RESULT: OK ($($toolRows.Count) tools, $($noteRows.Count) notes)"
exit 0
